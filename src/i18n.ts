const dictionaries: Record<Language, Record<Key, string>> = { en, ru };
let current: Language = "en";

export function resolveLanguage(setting: LanguageSetting): Language {
  if (setting !== "system") return setting;
  // First of the user's preferred languages that the interface supports.
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.toLowerCase().split("-")[0];
    if (base === "ru" || base === "en") return base;
  }
  return "en";
}

export function setLanguage(language: Language) { current = language; }
export function language(): Language { return current; }

export function t(key: Key, values: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

/** Count noun with the right plural form ("1 word", "5 слов"). */
export function plural(count: number, noun: "word" | "rule"): string {
  if (current === "en") return `${count === 1 ? noun : `${noun}s`}`;
  const forms = noun === "word" ? ["слово", "слова", "слов"] : ["правило", "правила", "правил"];
  const mod10 = count % 10, mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return forms[1];
  return forms[2];
}

/** Translate static markup: text (data-i18n), placeholders and aria-labels. */
export function translateDocument(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((node) => { node.innerHTML = t(node.dataset.i18n as Key); });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder as Key); });
  root.querySelectorAll<HTMLElement>("[data-i18n-label]").forEach((node) => { node.setAttribute("aria-label", t(node.dataset.i18nLabel as Key)); });
  document.documentElement.lang = current;
}
